// ============================================================
// POST /api/invitations/[token]/signup
//
// Public endpoint with valid invitation token.
// Creates a user account directly via Supabase Admin API with
// email_confirm: true, bypassing Supabase free-tier SMTP email
// rate limits ("email rate limit exceeded"), associates the user
// with the invited account and role, and redeems the invitation.
// ============================================================

import { NextResponse } from "next/server";
import { createClient as createAdminClient } from "@supabase/supabase-js";

import { hashInviteToken } from "@/lib/auth/invitations";
import {
  checkRateLimit,
  getClientIp,
  rateLimitResponse,
  RATE_LIMITS,
} from "@/lib/rate-limit";

function getAdminClient() {
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) {
    throw new Error("Missing Supabase admin credentials");
  }
  return createAdminClient(url, key, {
    auth: { autoRefreshToken: false, persistSession: false },
  });
}

export async function POST(
  request: Request,
  { params }: { params: Promise<{ token: string }> },
) {
  const ip = getClientIp(request);
  const limit = checkRateLimit(`invite-signup:${ip}`, RATE_LIMITS.invitationRedeem);
  if (!limit.success) return rateLimitResponse(limit);

  const { token } = await params;
  if (!token || typeof token !== "string") {
    return NextResponse.json({ error: "Invalid invitation token" }, { status: 400 });
  }

  let body: { email?: string; password?: string; fullName?: string };
  try {
    body = await request.json();
  } catch {
    return NextResponse.json({ error: "Invalid JSON body" }, { status: 400 });
  }

  const { email, password, fullName } = body;
  if (!email || typeof email !== "string" || !email.includes("@")) {
    return NextResponse.json({ error: "Valid email is required" }, { status: 400 });
  }
  if (!password || typeof password !== "string" || password.length < 6) {
    return NextResponse.json(
      { error: "Password must be at least 6 characters" },
      { status: 400 },
    );
  }

  const adminClient = getAdminClient();
  const tokenHash = hashInviteToken(token);

  // 1. Fetch & validate invitation
  const { data: inv, error: invError } = await adminClient
    .from("account_invitations")
    .select("*")
    .eq("token_hash", tokenHash)
    .maybeSingle();

  if (invError || !inv) {
    return NextResponse.json(
      { error: "Invitation not found or invalid" },
      { status: 404 },
    );
  }

  if (inv.accepted_at) {
    return NextResponse.json(
      { error: "Invitation has already been accepted" },
      { status: 400 },
    );
  }

  if (new Date(inv.expires_at) <= new Date()) {
    return NextResponse.json(
      { error: "Invitation has expired" },
      { status: 400 },
    );
  }

  // 2. Create the user with confirmed email directly via Admin API
  const { data: userData, error: createError } =
    await adminClient.auth.admin.createUser({
      email,
      password,
      email_confirm: true,
      user_metadata: { full_name: fullName || "" },
    });

  let userId: string;
  let orphanAccountId: string | undefined;

  if (createError) {
    if (
      createError.message.toLowerCase().includes("already been registered") ||
      createError.message.toLowerCase().includes("already registered")
    ) {
      // User exists in auth.users. Verify their password with signInWithPassword
      const anonClient = createAdminClient(
        process.env.NEXT_PUBLIC_SUPABASE_URL!,
        process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!,
      );
      const { data: signInData, error: signInError } =
        await anonClient.auth.signInWithPassword({ email, password });

      if (signInError || !signInData.user) {
        return NextResponse.json(
          {
            error:
              "A user with this email address is already registered. Please enter your existing account password to join, or click 'Sign in' below.",
          },
          { status: 400 },
        );
      }

      userId = signInData.user.id;
    } else {
      return NextResponse.json({ error: createError.message }, { status: 400 });
    }
  } else {
    userId = userData.user.id;
    // Get the profile generated by database trigger
    const { data: profile } = await adminClient
      .from("profiles")
      .select("account_id")
      .eq("user_id", userId)
      .maybeSingle();

    orphanAccountId = profile?.account_id;
  }

  // 3. Upsert / update the user profile to belong to inviter's account with the invited role
  const { error: profileUpdateError } = await adminClient
    .from("profiles")
    .upsert(
      {
        user_id: userId,
        account_id: inv.account_id,
        account_role: inv.role,
        full_name: fullName || email.split("@")[0],
        email,
      },
      { onConflict: "user_id" },
    );

  if (profileUpdateError) {
    console.error("[invite-signup] profile update error:", profileUpdateError);
  }

  // 4. Mark the invitation as accepted
  await adminClient
    .from("account_invitations")
    .update({
      accepted_at: new Date().toISOString(),
      accepted_by_user_id: userId,
    })
    .eq("id", inv.id);

  // 5. Delete orphan initial account ONLY if user's profile was successfully moved to target account
  if (orphanAccountId && orphanAccountId !== inv.account_id && !profileUpdateError) {
    const { data: currentProfile } = await adminClient
      .from("profiles")
      .select("account_id")
      .eq("user_id", userId)
      .maybeSingle();

    if (currentProfile?.account_id === inv.account_id) {
      await adminClient.from("accounts").delete().eq("id", orphanAccountId);
    }
  }

  return NextResponse.json({ ok: true, userId });
}
